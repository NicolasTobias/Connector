    private static func gcd(_ a: Int, _ b: Int) -> Int {
        var a = a
        var b = b
        while true {
            a = a % b
            if a == 0 { return b }
            b = b % a
            if b == 0 { return a }
        }
    }

    private static func lcm(_ a: Int, _ b: Int) -> Int {
        if a == 0 || b == 0 { return 1 }
        return (a * b) / gcd(a, b)
    }

    private static func generateKey(_ guid: [UInt8]) -> [UInt8] {
        var y = [UInt8](repeating: 0, count: 16)
        for i in 0..<4 {
            let l = lcm(Int(guid[i * 2]), Int(guid[i * 2 + 1]))
            let hi = Int((l & 0xFF00) >> 8)
            let lo = l & 0xFF
            y[i * 4] = table1[hi]
            y[i * 4 + 1] = table2[hi]
            y[i * 4 + 2] = table1[lo]
            y[i * 4 + 3] = table2[lo]
        }
        var sha = Insecure.SHA1()
        sha.update(data: fixed)
        sha.update(data: y)
        var key = [UInt8](sha.finalize())
        key.append(contentsOf: [UInt8](repeating: 0, count: 64 - key.count))
        return key
    }

    private static func computeHash(_ guid: [UInt8], _ data: Data) -> [UInt8] {
        let key = generateKey(guid)
        var inner = Insecure.SHA1()
        inner.update(data: key.map { $0 ^ 0x36 })
        inner.update(data: data)
        let innerDigest = [UInt8](inner.finalize())
        var outer = Insecure.SHA1()
        outer.update(data: key.map { $0 ^ 0x5c })
        outer.update(data: innerDigest)
        return [UInt8](outer.finalize())
    }

    private static let dbIdRange = 0x18..<0x20
    private static let schemeRange = 0x30..<0x32
    private static let unkRange = 0x32..<0x46
    private static let hashRange = 0x58..<0x6C

    private static func isValid(_ db: Data, _ guid: [UInt8]) -> Bool {
        guid.count == 8 && db.count >= 0x6C && db.prefix(4) == Data("mhbd".utf8)
    }

    public static func sign(_ db: inout Data, guid: [UInt8]) throws {
        guard guid.count == 8 else { throw SignError(description: "el GUID debe tener 8 bytes") }
        guard db.count >= 0x6C else { throw SignError(description: "iTunesDB too small to sign") }
        guard db.prefix(4) == Data("mhbd".utf8) else { throw SignError(description: "la cabecera no es mhbd") }
        let base = db.startIndex
        func span(_ r: Range<Int>) -> Range<Int> { (base + r.lowerBound)..<(base + r.upperBound) }
        let dbId = db.subdata(in: span(dbIdRange))
        let unk = db.subdata(in: span(unkRange))
        db.replaceSubrange(span(dbIdRange), with: [UInt8](repeating: 0, count: dbIdRange.count))
        db.replaceSubrange(span(unkRange), with: [UInt8](repeating: 0, count: unkRange.count))
        db.replaceSubrange(span(hashRange), with: [UInt8](repeating: 0, count: hashRange.count))
        db.replaceSubrange(span(schemeRange), with: [1, 0])
        let digest = computeHash(guid, db)
        db.replaceSubrange(span(hashRange), with: digest)
        db.replaceSubrange(span(dbIdRange), with: dbId)
        db.replaceSubrange(span(unkRange), with: unk)
    }

    public static func verify(_ db: Data, guid: [UInt8]) -> Bool {
        guard isValid(db, guid) else { return false }
        var copy = Data(db)
        let base = copy.startIndex
        let stored = [UInt8](copy.subdata(in: (base + hashRange.lowerBound)..<(base + hashRange.upperBound)))
        do { try sign(&copy, guid: guid) } catch { return false }
        let computed = [UInt8](copy.subdata(in: (base + hashRange.lowerBound)..<(base + hashRange.upperBound)))
        return computed == stored
    }

    public static func parseGUID(_ hex: String) -> [UInt8]? {
        var s = hex.trimmingCharacters(in: .whitespacesAndNewlines)
        if s.lowercased().hasPrefix("0x") { s.removeFirst(2) }
        guard s.count == 16 else { return nil }
        var bytes: [UInt8] = []
        var index = s.startIndex
        while index < s.endIndex {
            let next = s.index(index, offsetBy: 2)
            guard let b = UInt8(s[index..<next], radix: 16) else { return nil }
            bytes.append(b)
            index = next
        }
        return bytes
    }
